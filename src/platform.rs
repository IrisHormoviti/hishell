//! Host capabilities the core can use.

use std::path::{Path, PathBuf};
use std::sync::Arc;

use crate::entry::{Entry, EntryType};
use crate::execution::AppId;
use crate::item::IconRef;

#[derive(Clone, Debug, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub struct Mime(pub String);

impl Mime {
	pub fn as_str(&self) -> &str {
		&self.0
	}
}

#[derive(Clone, Debug, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub struct AppEntry {
	pub id: AppId,
	pub name: String,
	pub icon: Option<IconRef>,
	pub path: PathBuf,
	/// The label OPEN shows for this handler, from its desktop entry.
	pub open_label: Option<String>,
}

#[derive(Clone, Debug, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub struct Thumbnail {
	pub path: PathBuf,
	pub size: u32,
}

#[derive(Clone, Debug, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub struct ThumbnailRequest {
	pub path: PathBuf,
	pub size: u32,
}

#[derive(Clone, Debug, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub enum PlatformError {
	Unsupported(String),
	Io(String),
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub enum PortalState {
	Finished,
	Pending,
	Failed,
}

pub trait Launcher: Send + Sync {
	fn activate(&self, app: &AppId, uris: &[&Path]) -> Result<(), PlatformError>;
}

pub trait AppCatalog: Send + Sync {
	fn apps_for(&self, path: &Path) -> Vec<AppEntry>;
	fn default_app(&self, path: &Path) -> Option<AppEntry>;
	fn set_default(&self, mime: &str, app: &AppId) -> Result<(), PlatformError>;
}

pub trait MimeResolver: Send + Sync {
	fn mime_type(&self, path: &Path) -> Mime;
}

pub trait Thumbnailer: Send + Sync {
	/// Whether this thumbnailer can render `path`. Frontends use it to choose
	/// a thumbnail over an item's icon, so it must be cheap and free of I/O.
	fn supports(&self, path: &Path) -> bool {
		let _ = path;
		true
	}

	fn thumbnail(&self, request: &ThumbnailRequest) -> Result<Option<Thumbnail>, PlatformError>;
}

pub trait SoundPlayer: Send + Sync {
	fn play(&self, event: &str);
	fn set_volume(&self, volume: f32);
}

pub trait Portal: Send + Sync {
	fn open_with(&self, path: &Path) -> Result<(), PlatformError>;
	fn poll(&self) -> PortalState;
}

/// Host policy for locations whose contents the session owns.
///
/// The filesystem already refuses writes where it can. This covers the two
/// places where it says yes but the session says no: a folder a provider
/// daemon serves, and entries the image installed in the home. Both answers
/// come from the location, never from the item's own metadata, so a file
/// cannot make itself undeletable by saying so.
pub trait WritePolicy: Send + Sync {
	/// Whether `folder` is generated by a provider daemon. New items dropped
	/// there would land in the provider's staging queue and never appear.
	fn provider_serves(&self, folder: &Path) -> bool {
		let _ = folder;
		false
	}

	/// Whether `path` was installed by the image rather than created here.
	fn image_owns(&self, path: &Path) -> bool {
		let _ = path;
		false
	}
}

#[derive(Clone, Default)]
pub struct Platform {
	pub launcher: Option<Arc<dyn Launcher>>,
	pub apps: Option<Arc<dyn AppCatalog>>,
	pub mime: Option<Arc<dyn MimeResolver>>,
	pub thumbnails: Option<Arc<dyn Thumbnailer>>,
	pub sound: Option<Arc<dyn SoundPlayer>>,
	pub portal: Option<Arc<dyn Portal>>,
	pub writes: Option<Arc<dyn WritePolicy>>,
}

impl std::fmt::Debug for Platform {
	fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
		formatter
			.debug_struct("Platform")
			.field("launcher", &self.launcher.is_some())
			.field("apps", &self.apps.is_some())
			.field("mime", &self.mime.is_some())
			.field("thumbnails", &self.thumbnails.is_some())
			.field("sound", &self.sound.is_some())
			.field("portal", &self.portal.is_some())
			.field("writes", &self.writes.is_some())
			.finish()
	}
}

impl Platform {
	pub fn free_desktop() -> Self {
		Self {
			mime: Some(Arc::new(FreeDesktopMime)),
			apps: Some(Arc::new(FreeDesktopApps)),
			thumbnails: Some(Arc::new(crate::thumbnail::FreeDesktopThumbnailer)),
			..Self::default()
		}
	}

	pub fn mime_type(&self, path: &Path) -> Mime {
		match &self.mime {
			Some(resolver) => resolver.mime_type(path),
			None => Mime(String::from("application/octet-stream")),
		}
	}

	pub fn open_with(&self, _path: &Path) -> Result<(), PlatformError> {
		Err(PlatformError::Unsupported(String::from("portal")))
	}
}

#[derive(Default)]
pub struct FreeDesktopMime;

impl MimeResolver for FreeDesktopMime {
	fn mime_type(&self, path: &Path) -> Mime {
		Mime(resolved_mime(path))
	}
}

/// The content type for a path, letting a descriptor name it explicitly. A
/// provider uses that for a file whose extension says nothing about what it
/// holds, and the handler must follow the descriptor, not the extension.
fn resolved_mime(path: &Path) -> String {
	crate::descriptor::lookup(path)
		.and_then(|descriptor| descriptor.mime)
		.unwrap_or_else(|| {
			crate::icon::mime_for_path(path)
				.unwrap_or_else(|| String::from("application/octet-stream"))
		})
}

#[derive(Default)]
pub struct FreeDesktopApps;

impl AppCatalog for FreeDesktopApps {
	fn apps_for(&self, path: &Path) -> Vec<AppEntry> {
		let mime = resolved_mime(path);
		let mut apps = Vec::new();
		for (id, entry_path, fs_kind) in application_entries() {
			let Some(entry) = Entry::read(&entry_path, fs_kind) else {
				continue;
			};
			if entry.hidden || entry.no_display {
				continue;
			}
			if entry.entry_type != Some(EntryType::Application) {
				continue;
			}
			if !mime_matches(&entry, &mime) {
				continue;
			}
			apps.push(app_entry(&id, &entry));
		}
		apps
	}

	fn default_app(&self, path: &Path) -> Option<AppEntry> {
		let mime = resolved_mime(path);
		if let Some(id) = default_application(&mime)
			&& let Some(entry) = application_entry(&id)
		{
			return Some(entry);
		}
		// No registered default, or it names an entry that is gone: a handler
		// that declares the type is still a handler, so OPEN uses it instead
		// of reporting that nothing can open the file.
		self.apps_for(path).into_iter().next()
	}

	fn set_default(&self, mime: &str, app: &AppId) -> Result<(), PlatformError> {
		if mime.is_empty() || app.0.is_empty() {
			return Err(PlatformError::Unsupported(String::from(
				"empty mime or application",
			)));
		}
		let path = config_home().join("mimeapps.list");
		crate::config_parser::ConfigParser::set_value(&path, "Default Applications", mime, &app.0);
		Ok(())
	}
}

fn application_entry(id: &str) -> Option<AppEntry> {
	let (entry_path, fs_kind) = application_entries()
		.into_iter()
		.find(|(candidate, ..)| candidate == id)
		.map(|(_, path, fs_kind)| (path, fs_kind))?;
	let entry = Entry::read(&entry_path, fs_kind)?;
	Some(app_entry(id, &entry))
}

fn app_entry(id: &str, entry: &Entry) -> AppEntry {
	AppEntry {
		id: AppId(id.to_string()),
		name: entry.name.clone().unwrap_or_else(|| id.to_string()),
		icon: entry.icon_ref(),
		path: entry.path.clone(),
		open_label: entry.open_label.clone(),
	}
}

fn mime_matches(entry: &Entry, mime: &str) -> bool {
	// An entry that declares no MimeType() handles no file type; it is still
	// launchable from the applications folder, but it must not appear in
	// "Open With" or become the default for an arbitrary file.
	let Some(types) = entry_mime_types(entry) else {
		return false;
	};
	types.into_iter().any(|candidate| {
		candidate == mime
			|| candidate
				.strip_suffix("/*")
				.is_some_and(|prefix| mime.starts_with(&format!("{prefix}/")))
	})
}

fn entry_mime_types(entry: &Entry) -> Option<Vec<String>> {
	let text = std::fs::read_to_string(&entry.path).ok()?;
	let (sections, _) = crate::config_parser::ConfigParser::parse_str(&text, "<entry>");
	let values = sections.get("Desktop Entry")?;
	let value = match values.get("MimeType")? {
		crate::config_parser::ConfigValue::String(value) => value.clone(),
		_ => return None,
	};
	Some(
		value
			.split(';')
			.filter(|item| !item.is_empty())
			.map(str::to_string)
			.collect(),
	)
}

fn application_entries() -> Vec<(String, PathBuf, crate::item::FsKind)> {
	let mut entries: Vec<(String, PathBuf, crate::item::FsKind)> = Vec::new();
	for dir in data_home_dirs() {
		for entry in application_entries_in(&dir.join("applications")) {
			if !entries.iter().any(|(id, ..)| id == &entry.0) {
				entries.push(entry);
			}
		}
	}
	entries
}

fn application_entries_in(root: &Path) -> Vec<(String, PathBuf, crate::item::FsKind)> {
	let mut entries: Vec<(String, PathBuf, crate::item::FsKind)> = Vec::new();
	let mut pending = vec![root.to_path_buf()];
	while let Some(directory) = pending.pop() {
		let Ok(files) = std::fs::read_dir(directory) else {
			continue;
		};
		for file in files.flatten() {
			let path = file.path();
			let Some(name) = path.file_name().and_then(|name| name.to_str()) else {
				continue;
			};
			if name.starts_with('.') {
				continue;
			}
			if file.file_type().is_ok_and(|kind| kind.is_dir()) {
				let descriptor = path.join(".directory");
				if descriptor.is_file()
					&& let Some(entry) = Entry::read(&descriptor, crate::item::FsKind::Directory)
				{
					match entry.entry_type {
						Some(EntryType::Application) => entries.push((
							name.to_string(),
							descriptor,
							crate::item::FsKind::Directory,
						)),
						Some(EntryType::Directory) => pending.push(path),
						_ => {}
					}
				} else {
					pending.push(path);
				}
				continue;
			}
			// The id is the filename, extension included, for a flat entry.
			if is_application_entry(&path) {
				entries.push((name.to_string(), path, crate::item::FsKind::File));
			}
		}
	}
	entries
}

/// A file in an `applications/` directory that is an entry: a freedesktop
/// `.desktop`, or a ClamOS applet's `.directory` (same format, and hishell
/// treats it as an application like any other).
fn is_application_entry(path: &Path) -> bool {
	path.extension()
		.and_then(|extension| extension.to_str())
		.is_some_and(|extension| {
			extension.eq_ignore_ascii_case("desktop") || extension.eq_ignore_ascii_case("directory")
		})
}

fn default_application(mime: &str) -> Option<String> {
	// `mimeapps.list` lives in the config directories, but the desktop spec
	// also allows it beside the applications it names. A frontend can ship
	// its defaults in a data directory's `applications/`, which is on
	// XDG_DATA_DIRS; the user's own config directories still win.
	let config_lists = config_dirs()
		.into_iter()
		.map(|dir| dir.join("mimeapps.list"));
	let data_lists = data_home_dirs()
		.into_iter()
		.map(|dir| dir.join("applications/mimeapps.list"));
	for path in config_lists.chain(data_lists) {
		let Ok(text) = std::fs::read_to_string(path) else {
			continue;
		};
		let (sections, _) = crate::config_parser::ConfigParser::parse_str(&text, "<mimeapps>");
		for section in ["Default Applications", "Added Associations"] {
			if let Some(value) = sections.get(section).and_then(|values| values.get(mime))
				&& let crate::config_parser::ConfigValue::String(value) = value
			{
				let first = value.split(';').find(|item| !item.is_empty())?;
				return Some(first.to_string());
			}
		}
	}
	None
}

fn data_home_dirs() -> Vec<PathBuf> {
	let mut dirs = Vec::new();
	if let Some(dir) = dirs::data_dir() {
		dirs.push(dir);
	}
	if let Ok(value) = std::env::var("XDG_DATA_DIRS") {
		for dir in value.split(':').filter(|dir| !dir.is_empty()) {
			dirs.push(PathBuf::from(dir));
		}
	} else {
		dirs.push(PathBuf::from("/usr/local/share"));
		dirs.push(PathBuf::from("/usr/share"));
	}
	dirs
}

fn config_dirs() -> Vec<PathBuf> {
	let mut dirs = Vec::new();
	if let Some(dir) = dirs::config_dir() {
		dirs.push(dir);
	}
	if let Ok(value) = std::env::var("XDG_CONFIG_DIRS") {
		for dir in value.split(':').filter(|dir| !dir.is_empty()) {
			dirs.push(PathBuf::from(dir));
		}
	} else {
		dirs.push(PathBuf::from("/etc/xdg"));
	}
	dirs
}

fn config_home() -> PathBuf {
	dirs::config_dir().unwrap_or_else(|| PathBuf::from("/etc/xdg"))
}

#[cfg(test)]
mod tests {
	use super::*;

	#[test]
	fn mime_uses_the_extension_table() {
		let root = std::env::temp_dir().join(format!("hishell-platform-{}", std::process::id()));
		std::fs::create_dir_all(&root).unwrap();
		let image = root.join("photo.png");
		std::fs::write(&image, b"png").unwrap();
		assert_eq!(FreeDesktopMime.mime_type(&image).0, "image/png");
		std::fs::remove_dir_all(root).unwrap();
	}

	#[test]
	fn an_applet_directory_entry_is_an_application_entry() {
		assert!(is_application_entry(Path::new(
			"/home/.local/share/applications/clam-text-editor.directory"
		)));
		assert!(is_application_entry(Path::new(
			"/usr/share/applications/clam-image-viewer.desktop"
		)));
		assert!(!is_application_entry(Path::new("/home/notes.txt")));
	}

	#[test]
	fn a_bundle_folder_is_an_application_entry() {
		let root =
			std::env::temp_dir().join(format!("hishell-platform-bundle-{}", std::process::id()));
		let applications = root.join("applications");
		std::fs::create_dir_all(applications.join("clam-thing")).unwrap();
		std::fs::write(
			applications.join("clam-thing/.directory"),
			"[Desktop Entry]\nType=Application\nName=Thing\nExec=thing\n",
		)
		.unwrap();
		let bundled_entry = applications.join("clam-thing/internal/nested-app");
		std::fs::create_dir_all(&bundled_entry).unwrap();
		std::fs::write(
			bundled_entry.join(".directory"),
			"[Desktop Entry]\nType=Application\nName=Internal\n",
		)
		.unwrap();
		std::fs::create_dir_all(applications.join("plain")).unwrap();
		let category = applications.join("settings");
		let nested_app = category.join("clam-config-editor");
		std::fs::create_dir_all(&nested_app).unwrap();
		std::fs::write(
			category.join(".directory"),
			"[Desktop Entry]\nType=Directory\nName=Settings\n",
		)
		.unwrap();
		std::fs::write(
			nested_app.join(".directory"),
			"[Desktop Entry]\nType=Application\nName=Config editor\nMimeType=application/x-clam-config;\n",
		)
		.unwrap();
		std::fs::write(
			applications.join("flat.desktop"),
			"[Desktop Entry]\nType=Application\n",
		)
		.unwrap();
		std::fs::write(
			applications.join("flat.directory"),
			"[Desktop Entry]\nType=Application\n",
		)
		.unwrap();

		let entries = application_entries_in(&applications);
		assert!(entries.iter().any(|(id, path, kind)| {
			id == "clam-thing"
				&& path.ends_with("clam-thing/.directory")
				&& *kind == crate::item::FsKind::Directory
		}));
		assert!(entries.iter().any(|(id, ..)| id == "flat.desktop"));
		assert!(entries.iter().any(|(id, ..)| id == "flat.directory"));
		assert!(entries.iter().any(|(id, path, kind)| {
			id == "clam-config-editor"
				&& path.ends_with("settings/clam-config-editor/.directory")
				&& *kind == crate::item::FsKind::Directory
		}));
		assert!(!entries.iter().any(|(id, ..)| id == "nested-app"));
		assert!(!entries.iter().any(|(id, ..)| id == "plain"));
		std::fs::remove_dir_all(root).unwrap();
	}

	#[test]
	fn an_entry_without_mime_types_handles_nothing() {
		let root = std::env::temp_dir().join(format!(
			"hishell-platform-mime-{}",
			std::process::id()
		));
		std::fs::create_dir_all(&root).unwrap();
		let file = root.join("plain.desktop");
		std::fs::write(
			&file,
			"[Desktop Entry]\nType=Application\nName=Plain\nExec=true\n",
		)
		.unwrap();
		let entry = Entry::read(&file, crate::item::FsKind::File).unwrap();
		assert!(!mime_matches(&entry, "text/plain"));
		std::fs::remove_dir_all(root).unwrap();
	}

	#[test]
	fn missing_capabilities_fall_back() {
		let platform = Platform::default();
		assert_eq!(
			platform.mime_type(Path::new("/tmp/a.png")).0,
			"application/octet-stream"
		);
		assert!(platform.open_with(Path::new("/tmp/a.png")).is_err());
	}
}
